
let x = 10;
let y = 5;
let hasil;

// operator aritmatika

// penjumlahan
hasil = y + x;
console.log(hasil);

// pengurangan
hasil = x - y;
console.log(hasil);

// pembagian
hasil = y / x;
console.log(hasil);

// perkalian
hasil = y * x;
console.log(hasil);


// operator logika

// AND (&&) => jika dua nilai bernilai true
x = true;
y = false;

hasil = x && y;
console.log(hasil);

// OR (||) => jika salah satu nilai bernilai true
hasil = x || y;
console.log(hasil);


// operator perbandingan

// gunakan kembali nilai angka
x = 10;
y = 5;

// sama dengan (==)
hasil = (x == y);
console.log(hasil);

// tidak sama dengan (!=)
hasil = (x != y);
console.log(hasil);

// lebih besar (>)
hasil = (x > y);
console.log(hasil);

// kurang dari (<)
hasil = (x < y);
console.log(hasil);

// lebih besar dari sama dengan (>=)
hasil = (x >= y);
console.log(hasil);

// kurang dari sama dengan (<=)
hasil = (x <= y);
console.log(hasil);
